/**
 * Regenerates `project.txt` — a single-file bundle of the whole codebase, meant
 * to be pasted into (or uploaded to) an AI assistant that has no access to the
 * repository. It replaces the old repomix output, which went stale the moment
 * the code was reorganized.
 *
 *     node tools/bundle-project.mjs
 *
 * What goes in: every source and documentation file (see INCLUDE/EXCLUDE below).
 * What stays out: images, the generated bundle itself, the pre-refactor snapshot
 * in `_legacy/`, and anything under `.git`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'project.txt');

const INCLUDE_EXT = new Set(['.js', '.mjs', '.css', '.html', '.md', '.json', '.yml', '.yaml']);
const EXCLUDE_DIRS = new Set(['.git', 'node_modules', '_legacy', '.github/ISSUE_TEMPLATE']);
const EXCLUDE_FILES = new Set(['project.txt', 'CHANGELOG.md']);

/** Files listed first, because they orient a reader fastest. */
const PRIORITY = ['CLAUDE.md', 'AGENTS.md', 'README.md', 'ARCHITECTURE.md', 'DATA-MODEL.md'];

function walk(dir, acc = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name);
    const rel = path.relative(ROOT, abs);
    if (entry.isDirectory()) {
      if (EXCLUDE_DIRS.has(entry.name) || EXCLUDE_DIRS.has(rel)) continue;
      walk(abs, acc);
    } else {
      if (EXCLUDE_FILES.has(rel) || EXCLUDE_FILES.has(entry.name)) continue;
      if (!INCLUDE_EXT.has(path.extname(entry.name))) continue;
      acc.push(rel);
    }
  }
  return acc;
}

const files = walk(ROOT).sort((a, b) => {
  const pa = PRIORITY.indexOf(a);
  const pb = PRIORITY.indexOf(b);
  if (pa !== -1 || pb !== -1) return (pa === -1 ? 999 : pa) - (pb === -1 ? 999 : pb);
  return a.localeCompare(b);
});

const bar = '='.repeat(64);
const out = [];

out.push(bar);
out.push('AUH Internal Medicine — Residents Dashboard: full source bundle');
out.push(bar);
out.push('');
out.push('Generated by tools/bundle-project.mjs — do not edit by hand.');
out.push('Purpose: give an AI assistant the whole project in one file.');
out.push('');
out.push('Start with CLAUDE.md and AGENTS.md: they carry the conventions and the');
out.push('invariants. ARCHITECTURE.md maps the code, DATA-MODEL.md explains the data,');
out.push('docs/DATA-CONTRACT.md lists every sheet column the app depends on.');
out.push('');
out.push('Excluded here: images, CHANGELOG.md (long history — read it in the repo),');
out.push('and _legacy/ (a pre-refactor snapshot kept only for reference).');
out.push('');
out.push(`Files included: ${files.length}`);
out.push('');
out.push(bar);
out.push('FILE INDEX');
out.push(bar);
files.forEach(f => out.push(`  ${f}`));
out.push('');

for (const rel of files) {
  const content = fs.readFileSync(path.join(ROOT, rel), 'utf8').replace(/\s+$/, '');
  out.push('');
  out.push(bar);
  out.push(`FILE: ${rel}`);
  out.push(bar);
  out.push(content);
}

out.push('');
fs.writeFileSync(OUT, out.join('\n'), 'utf8');

const kb = Math.round(fs.statSync(OUT).size / 1024);
console.log(`project.txt regenerated — ${files.length} files, ${kb} KB`);
